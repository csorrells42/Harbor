import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const [repository,pattern,stage]=process.argv.slice(2);
if(!/^[\w-]+\/[\w.-]+$/.test(repository)||!stage)throw new Error('Repository and stage are required');
const response=await fetch(`https://api.github.com/repos/${repository}/releases/latest`,{headers:{'User-Agent':'Harbor-Portable'},signal:AbortSignal.timeout(30000)});
if(!response.ok)throw new Error(`Release lookup failed: ${response.status}`);
const release=await response.json();
const assets=release.assets.filter(a=>new RegExp(pattern).test(a.name));
if(assets.length!==1)throw new Error('A unique Windows release asset was not found');
const asset=assets[0];
if(!/^sha256:[a-f0-9]{64}$/i.test(asset.digest))throw new Error('Release has no SHA256 digest; current version retained');
const download=await fetch(asset.browser_download_url,{signal:AbortSignal.timeout(300000)});
if(!download.ok)throw new Error(`Release download failed: ${download.status}`);
const bytes=Buffer.from(await download.arrayBuffer());
if(`sha256:${createHash('sha256').update(bytes).digest('hex')}`!==asset.digest.toLowerCase())throw new Error('Release checksum mismatch');
const archive=path.join(stage,'harbor-release.zip');await fs.writeFile(archive,bytes);
const python=path.join(process.env.HARBOR_PORTABLE_ROOT,'runtimes/python/python.exe');
await promisify(execFile)(python,['-c',"import pathlib,sys,zipfile; root=pathlib.Path(sys.argv[2]).resolve(); z=zipfile.ZipFile(sys.argv[1]); files=z.infolist(); assert all((root / f.filename).resolve().is_relative_to(root) for f in files), 'Archive escapes stage'; z.extractall(root)",archive,stage],{windowsHide:true,env:process.env});
await fs.unlink(archive);
await fs.writeFile(path.join(stage,'harbor-version.json'),JSON.stringify({version:release.tag_name,repository,asset:asset.name,sha256:asset.digest,observedAt:new Date().toISOString()},null,2));
console.log(`Verified official ${repository} ${release.tag_name} release`);
